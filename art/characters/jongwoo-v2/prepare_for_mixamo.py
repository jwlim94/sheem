"""Prepares the Meshy 7.1 Flagship hoodie character for Mixamo auto-rigging.
Run: Blender -b --python art/characters/jongwoo-v2/prepare_for_mixamo.py

Input:  source/meshy-flagship.glb (Meshy AI, generated by the user; A-pose,
        1.9 m, 547k triangles, 2k colour/roughness-metal/normal maps). Its hands
        have five separate fingers, which is why it replaces the hoodie
        character whose mittens Mixamo rigged with a thumb and index only.
Output: mixamo/jongwoo-v2-upload.fbx (feet on the ground, ~60k triangles,
        colour texture embedded) and, with PREVIEW=<dir>, a front render.

Upload it to Mixamo with the Standard Skeleton (65 bones, with fingers).
"""
import os
from pathlib import Path

import bmesh
import bpy

HERE = Path(__file__).resolve().parent
SRC = HERE / 'source/meshy-flagship.glb'
OUT = HERE / 'mixamo/jongwoo-v2-upload.fbx'
TARGET_FACES = 60000

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(SRC))
obj = next(o for o in bpy.context.scene.objects if o.type == 'MESH')
for o in list(bpy.context.scene.objects):
    if o is not obj:
        bpy.data.objects.remove(o, do_unlink=True)
obj.parent = None
bpy.ops.object.select_all(action='DESELECT')
obj.select_set(True)
bpy.context.view_layer.objects.active = obj
bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
obj.name = 'JongwooV2'

# Meshy splits vertices along every UV seam: weld them first, or decimating
# pulls the seams apart into cracks (UVs live on loops, so they survive).
bm = bmesh.new()
bm.from_mesh(obj.data)
n0 = len(bm.verts)
bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
# Feet on the ground, centred over the origin.
zs = [v.co.z for v in bm.verts]
xs = [v.co.x for v in bm.verts]
ys = [v.co.y for v in bm.verts]
cx, cy, z0 = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2, min(zs)
for v in bm.verts:
    v.co.x -= cx
    v.co.y -= cy
    v.co.z -= z0
bm.to_mesh(obj.data)
bm.free()
print('WELD', n0, '->', len(obj.data.vertices))

dec = obj.modifiers.new('Lighter', 'DECIMATE')
dec.ratio = min(1.0, TARGET_FACES / len(obj.data.polygons))
dec.use_collapse_triangulate = True
bpy.ops.object.modifier_apply(modifier=dec.name)
for p in obj.data.polygons:
    p.use_smooth = True
print('FACES', len(obj.data.polygons), 'HEIGHT', round(obj.dimensions.z, 3))

# Mixamo only needs the colour: drop the metal/roughness and normal maps from
# the upload (the web build takes them from the source again).
mat = obj.data.materials[0]
nt = mat.node_tree
bsdf = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
for name in ('Metallic', 'Roughness', 'Normal'):
    for link in list(bsdf.inputs[name].links):
        nt.links.remove(link)
base = bsdf.inputs['Base Color'].links[0].from_node
base.image.name = 'jongwoo_v2_basecolor'
base.image.filepath_raw = str(HERE / 'source/basecolor.png')
base.image.file_format = 'PNG'
base.image.save()

OUT.parent.mkdir(parents=True, exist_ok=True)
bpy.ops.export_scene.fbx(filepath=str(OUT), use_selection=True, object_types={'MESH'},
                         path_mode='COPY', embed_textures=True, apply_unit_scale=True)
print('FBX', OUT, OUT.stat().st_size)

if os.environ.get('PREVIEW'):
    from mathutils import Vector
    sc = bpy.context.scene
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('c'))
    sc.collection.objects.link(cam)
    sc.camera = cam
    sun = bpy.data.objects.new('sun', bpy.data.lights.new('sun', 'SUN'))
    sun.data.energy = 3
    sun.rotation_euler = (0.8, 0.1, 0.3)
    sc.collection.objects.link(sun)
    w = bpy.data.worlds.new('w')
    sc.world = w
    w.use_nodes = True
    w.node_tree.nodes['Background'].inputs[1].default_value = 0.8
    try:
        sc.render.engine = 'BLENDER_EEVEE_NEXT'
    except TypeError:
        sc.render.engine = 'BLENDER_EEVEE'
    sc.render.resolution_x, sc.render.resolution_y = 500, 700
    c = Vector((0, 0, obj.dimensions.z / 2))
    cam.location = c + Vector((0, -6, 0))
    cam.rotation_euler = (c - cam.location).to_track_quat('-Z', 'Y').to_euler()
    cam.data.lens = 50
    sc.render.filepath = os.path.join(os.environ['PREVIEW'], 'v2_upload_front.png')
    bpy.ops.render.render(write_still=True)
    # The right hand, close.
    hx = min(v.co.x for v in obj.data.vertices)
    hand = [v.co for v in obj.data.vertices if v.co.x < hx * 0.8]
    hc = sum(hand, Vector()) / len(hand)
    sc.render.resolution_x = sc.render.resolution_y = 450
    cam.location = hc + Vector((0, -0.6, 0.05))
    cam.rotation_euler = (hc - cam.location).to_track_quat('-Z', 'Y').to_euler()
    cam.data.lens = 85
    sc.render.filepath = os.path.join(os.environ['PREVIEW'], 'v2_upload_hand.png')
    bpy.ops.render.render(write_still=True)
