// Shallows are broad color volumes, not exact collision/foam boundaries.
export const archipelagoShallowsGLSL = distantIslands
  .map((island) => {
    const [x, z] = island.position,
      [rx, rz] = island.radius;
    return `d = smoothIslandDistance(d, (length((p - vec2(${x.toFixed(1)}, ${(-z).toFixed(1)})) / vec2(${rx.toFixed(1)}, ${rz.toFixed(1)})) - 1.) * ${Math.min(rx, rz).toFixed(1)}, 3.);`;
  })
  .join('\n');
